"""Build the IEEE two-column journal version of the manuscript (IEEEtran, e.g. for IEEE TGRS or JSTARS).

The article-class LaTeX in ``latex_source/`` stays the master copy. This script
writes ``ieee_source/``: the same sections and figures in ``IEEEtran``
journal layout:

* a single-paragraph abstract of at most 250 words, as IEEE requires, and
  Index Terms;
* numbered citations (natbib with ``IEEEtranN``, so ``\\citet`` still gives
  "Author et al. [n]");
* pandoc's ``longtable`` tables become two-column-wide ``table*`` floats with
  booktabs rules, and figures become ``figure*`` floats;
* IEEE back matter (code and data availability, acknowledgment).

IEEEtran ships with TeX Live and MiKTeX, so nothing needs downloading.

Usage (from the repository root):
    python 08_manuscript/md_to_latex.py
    python 08_manuscript/make_ieee.py
    cd 08_manuscript/ieee_source && latexmk -pdf manuscript.tex
"""

