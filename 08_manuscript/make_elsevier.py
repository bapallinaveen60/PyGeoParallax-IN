def convert(name, tex):
    if name == "figures":
        for label in MAP_FIGURES:
            tex = re.sub(r"(\\caption\{.*?)\}(\s*\\label\{" + re.escape(label) + r"\})",
                         lambda m: m.group(1) + MAP_NOTE + "}" + m.group(2), tex, count=1, flags=re.S)
    return tex


def main():
    for h in HIGHLIGHTS:
        assert len(h) <= 85, (len(h), h)
    words = len(re.sub(r"\\[a-zA-Z]+|[{}$\\]", " ", ABSTRACT).split())
    assert words <= 250, words

    (OUT / "sections").mkdir(parents=True, exist_ok=True)
    for name in SECTIONS:
        tex = (SRC / "sections" / f"{name}.tex").read_text(encoding="utf-8")
        (OUT / "sections" / f"{name}.tex").write_text(convert(name, tex), encoding="utf-8", newline="\n")
    shutil.copytree(SRC / "figures", OUT / "figures", dirs_exist_ok=True)
    shutil.copy2(SRC / "references.bib", OUT / "references.bib")

    front = (f"\\title{{{TITLE}}}\n\n"
             f"\\author{{Naveen Bapalli\\corref{{cor1}}}}\n\\ead{{{EMAIL}}}\n"
             f"\\cortext[cor1]{{Corresponding author.}}\n\\affiliation{{{ADDRESS}}}\n\n"
             f"\\begin{{abstract}}\n{ABSTRACT}\n\\end{{abstract}}\n\n"
             "\\begin{keyword}\n" + " \\sep ".join(KEYWORDS) + "\n\\end{keyword}\n\n"
             "\\end{frontmatter}\n\n\\linenumbers\n\n")
    body = "".join(("\\appendix\n" if name == "appendix" else "") + f"\\input{{sections/{name}}}\n" for name in SECTIONS)
    (OUT / "manuscript.tex").write_text(PREAMBLE + front + body + BACKMATTER, encoding="utf-8", newline="\n")
    (OUT / "highlights.txt").write_text("".join(f"- {h}\n" for h in HIGHLIGHTS), encoding="utf-8", newline="\n")
    print(f"wrote {OUT / 'manuscript.tex'} (abstract {words} words) and highlights.txt "
          f"({', '.join(str(len(h)) for h in HIGHLIGHTS)} characters)")


if __name__ == "__main__":
    main()
