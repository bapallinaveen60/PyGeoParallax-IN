"""Build the Atmospheric Measurement Techniques (Copernicus) version of the manuscript.

The article-class LaTeX in ``latex_source/`` stays the master copy. This script
writes ``amt_source/``: the same sections and figures, converted to the
Copernicus template (``copernicus.cls``, ``amt`` journal, ``manuscript``
option with line numbers):

* Introduction and Conclusions use the template's ``\\introduction`` and
  ``\\conclusions`` headings;
* pandoc's ``longtable`` tables become ``table*`` floats with the template's
  ``\\tophline``, ``\\middlehline`` and ``\\bottomhline`` rules;
* figures float at the top of the page;
* the back matter uses the template's commands (code and data availability,
  author contributions, competing interests, acknowledgements);
* references use ``copernicus.bst``.

The Copernicus class files are not part of this repository. Download the
Copernicus LaTeX package (https://publications.copernicus.org/Copernicus_LaTeX_Package.zip)
and pass the unpacked folder with ``--template`` once; the files are copied
into ``amt_source/``.

Usage (from the repository root):
    python 08_manuscript/md_to_latex.py
    python 08_manuscript/make_amt.py [--template <copernicus package folder>]
    cd 08_manuscript/amt_source && latexmk -pdf manuscript.tex
"""

