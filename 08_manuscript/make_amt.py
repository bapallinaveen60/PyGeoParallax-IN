def convert_tables(tex):
    """pandoc longtable -> Copernicus table* with \\tophline / \\middlehline / \\bottomhline."""

    def repl(m):
        block = m.group(0)
        spec = re.match(r"\\begin\{longtable\}\[\]\{(.*?)\}\s*\n\\caption", block, flags=re.S).group(1)
        caption = re.search(r"\\caption\{(.*?)\}\\label\{([^}]*)\}\\\\\*?", block, flags=re.S)
        header = re.search(r"\\toprule\\noalign\{\}\n(.*?)\\midrule\\noalign\{\}", block, flags=re.S).group(1)
        body = re.search(r"\\endlastfoot\n(.*?)\\end\{longtable\}", block, flags=re.S).group(1)
        rows = lambda t: re.sub(r"\\\\\*", r"\\\\", t).strip()  # noqa: E731
        return ("\\begin{table*}[t]\n"
                f"\\caption{{{caption.group(1)}}}\\label{{{caption.group(2)}}}\n"
                f"\\begin{{tabular}}{{{spec}}}\n\\tophline\n{rows(header)}\n\\middlehline\n{rows(body)}\n"
                "\\bottomhline\n\\end{tabular}\n\\end{table*}")

    return re.sub(r"\\begin\{longtable\}.*?\\end\{longtable\}", repl, tex, flags=re.S)


def convert(name, tex):
    if name == "introduction":
        tex = tex.replace("\\section{Introduction}", "\\introduction", 1)
    if name == "conclusions":
        tex = tex.replace("\\section{Conclusions}", "\\conclusions", 1)
    tex = re.sub(r"\\begin\{figure\}\[tbp\]", r"\\begin{figure*}[t]", tex)
    tex = tex.replace("\\end{figure}", "\\end{figure*}")
    return convert_tables(tex)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--template", help="unpacked Copernicus LaTeX package (copied once into amt_source/)")
    args = ap.parse_args(argv)

    (OUT / "sections").mkdir(parents=True, exist_ok=True)
    if args.template:
        for f in TEMPLATE_FILES:
            shutil.copy2(Path(args.template) / f, OUT / f)
    missing = [f for f in TEMPLATE_FILES if not (OUT / f).exists()]
    if missing:
        raise SystemExit(f"missing Copernicus files in {OUT}: {missing}; run once with --template")

    for name in SECTIONS:
        tex = (SRC / "sections" / f"{name}.tex").read_text(encoding="utf-8")
        (OUT / "sections" / f"{name}.tex").write_text(convert(name, tex), encoding="utf-8", newline="\n")
    shutil.copytree(SRC / "figures", OUT / "figures", dirs_exist_ok=True)
    shutil.copy2(SRC / "references.bib", OUT / "references.bib")

    body = "".join(f"\\input{{sections/{name}}}\n" for name in SECTIONS)
    (OUT / "manuscript.tex").write_text(PREAMBLE + body + BACKMATTER, encoding="utf-8", newline="\n")
    print(f"wrote {OUT / 'manuscript.tex'}")


if __name__ == "__main__":
    main()
